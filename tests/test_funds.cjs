const assert=require('node:assert/strict');
const {fundExposure,fundKey,fundAllocation}=require('../portfolio/app/static/funds.js');
const etf={symbol:'ANY',exchange:'TEST',currency:'USD',name:'Any ETF',value:'1000',quantity:'2',categories:{asset_type:'ETF'}};
const composition={...etf,holdings:[{name:'First',weight:'60',sector:'Tech',country:'US'},{name:'Second',weight:'30',sector:'Banks',country:'NL'}]};
let rows=fundExposure([etf],[composition]);
assert.equal(rows.length,3);
assert.equal(rows.reduce((sum,p)=>sum+p.value,0),1000);
assert.equal(rows[0].value,600);
assert.equal(rows[2].categories.country,'ETF niet uitgesplitst');
assert.ok(!rows.some(p=>p.name==='Any ETF'));
assert.equal(fundExposure([etf],[])[0].value,1000);
assert.equal(fundExposure([{...etf,value:null}],[composition]).length,0);
const euro={...etf,currency:'EUR',native_currency:'USD',value:'900'};
assert.equal(fundKey(euro),fundKey(etf));
assert.equal(fundExposure([euro],[composition])[0].value,540);
const signed={...composition,holdings:[{name:'Bank',weight:'100.01',sector:'Banks',country:'NL'},{name:'Cash',weight:'-0.01',sector:'Cash',country:'NL'}]};
rows=fundExposure([etf],[signed]);
assert.ok(rows[1].value<0);
assert.ok(Math.abs(rows.reduce((sum,p)=>sum+p.value,0)-1000)<1e-9);
rows=fundExposure([etf,{symbol:'DIRECT',value:'500',currency:'USD',categories:{sector:'Banks',country:'NL'}}],[composition]);
assert.equal(rows.reduce((sum,p)=>sum+p.value,0),1500);
assert.equal(etf.value,'1000');
global.fundExposure=fundExposure;
global.state={fund_compositions:[composition]};
const {reportAnalytics}=require('../portfolio/app/static/reports.js');
const analytics=reportAnalytics([{...etf,cost:'800',realised:'10',dividend:'5'}],[],'2026').groups[0];
assert.equal(analytics.total.value,1000);
assert.equal(analytics.total.profit,215);
assert.equal(analytics.allocation[0].name,'First');
assert.equal(analytics.sectors.find(p=>p.name==='Tech').value,600);
assert.equal(analytics.countries.find(p=>p.name==='NL').value,300);
assert.equal(analytics.holdings[0].name,'Any ETF');
console.log('ETF look-through preserves totals, residuals, signed cash, native identity and real ETF returns.');

const known={...composition,holdings:[{name:'First',symbol:'A',exchange:'NYSE',currency:'USD',weight:'100'}]};
const second={...etf,symbol:'OTHER'};
const merged=fundAllocation(fundExposure([etf,second],[known,{...known,symbol:'OTHER'}]));
assert.equal(merged.length,1);assert.equal(merged[0].value,2000);
